// Embeds pdf.js (legacy build) into a TS module so the offline app can read PDF statements inside a hidden WebView.
const fs = require('fs'); const path = require('path');
let dir;
for (const base of [path.join(__dirname, '..'), path.join(__dirname, '../../..')]) {
  try { dir = path.dirname(require.resolve('pdfjs-dist/package.json', { paths: [base] })); break; } catch { /* next */ }
}
if (!dir) { console.warn('pdfjs-dist not found — run npm install at the repo root first'); process.exit(0); }
const main = fs.readFileSync(path.join(dir, 'legacy/build/pdf.min.mjs'), 'utf8');
const worker = fs.readFileSync(path.join(dir, 'legacy/build/pdf.worker.min.mjs'), 'utf8');
const out = path.join(__dirname, '../src/local/pdfjs-assets.generated.ts');
fs.writeFileSync(out, `// generated by scripts/build-pdfjs.cjs — do not edit\nexport const PDFJS_MAIN = ${JSON.stringify(main)};\nexport const PDFJS_WORKER = ${JSON.stringify(worker)};\n`);
console.log('pdf.js embedded →', path.relative(process.cwd(), out));
